export function calculateEndOfSessionXP(yesCount: number): { xp: number; label: string } {
  if (yesCount <= 0) {
    return { xp: 0, label: '0 XP' };
  } else if (yesCount <= 2) {
    return { xp: 1, label: 'Mark 1 Experience box' };
  } else {
    return { xp: 2, label: 'Mark 2 Experience boxes' };
  }
}
